export function databaseConnectionOptions(connectionString: string, production: boolean): PoolConfig {
  if (!production) return { connectionString };
  const url = new URL(connectionString);
  if (!["postgres:", "postgresql:"].includes(url.protocol)) throw new Error("Invalid database connection protocol.");
  // pg connection-string SSL parameters override the explicit SSL object.
  // Remove them so even an inherited sslmode=disable cannot weaken production.
  for (const key of ["ssl", "sslmode", "sslrootcert", "sslcert", "sslkey", "uselibpqcompat"]) url.searchParams.delete(key);
  return {
    connectionString: url.toString(),
    ssl: { rejectUnauthorized: true, ca: [...rootCertificates, supabaseRootCa] },
  };
}

